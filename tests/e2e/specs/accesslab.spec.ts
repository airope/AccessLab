// Disposable credentials generated by this project's bootstrap, never user credentials.
function passwordFor(user: string): string {
  const path =
    process.env.ACCESSLAB_CREDENTIALS ??
    resolve(root, ".local/credentials.json");
  const data = JSON.parse(readFileSync(path, "utf8"));
  const value = data.users?.[user]?.password;
  if (typeof value !== "string" || !value)
    throw new Error(
      "Generated fixture credentials are missing. Run the documented bootstrap.",
    );
  return value;
}

async function login(browser: Browser, user: string, expectedStatus = 200) {
  const context = await browser.newContext({
    baseURL,
    ignoreHTTPSErrors: true,
    viewport: { width: 1440, height: 1000 },
  });
  const page = await context.newPage();
  await page.goto(`${baseURL}/auth/login?returnUrl=/api/session`);
  await page.locator('input[name="username"]').fill(user);
  try {
    await page.locator('input[name="password"]').fill(passwordFor(user));
  } catch {
    throw new Error(
      "Generated credential input unavailable; credential value omitted.",
    );
  }
  await page.locator("#kc-login").click();
  await page.waitForURL(
    (url) => url.origin === baseURL && !url.pathname.startsWith("/signin"),
    { timeout: 30_000 },
  );
  await expect
    .poll(async () => (await context.request.get("/api/session")).status())
    .toBe(expectedStatus);
  return { context, page };
}

async function mutate(
  context: BrowserContext,
  path: string,
  data: unknown,
  key = crypto.randomUUID(),
) {
  const csrf = await context.request.get("/api/csrf");
  expect(csrf.status(), "CSRF endpoint").toBe(200);
  const token = (await csrf.json()).token;
  return context.request.post(path, {
    data,
    headers: { "X-CSRF-TOKEN": token, "Idempotency-Key": key },
  });
}

async function jsonOk(
  response: Awaited<ReturnType<typeof mutate>>,
  codes = [200],
) {
  expect(codes, `HTTP status ${response.status()}`).toContain(
    response.status(),
  );
  if (response.status() === 204) return null;
  return response.json();
}

async function preview(
  context: BrowserContext,
  operation: string,
  extra: Record<string, unknown> = {},
) {
  return jsonOk(
    await mutate(context, "/api/previews", {
      accountId: ids.alice,
      groupId: "analysis",
      operation,
      startsAt: new Date(Date.now() - 60_000).toISOString(),
      endsAt: new Date(Date.now() + 86_400_000).toISOString(),
      reason: "Reproducible research access verification",
      ...extra,
    }),
  );
}

async function readJson(context: BrowserContext, path: string) {
  return jsonOk(await context.request.get(path));
}

async function cleanupRequest(
  context: BrowserContext,
  reviewer: BrowserContext,
  requestId: string | undefined,
  beforeIds: string[],
) {
  await cleanupRun({
    requestId,
    beforeIds,
    get: (path) => readJson(context, path),
    post: async (path, data) => jsonOk(await mutate(context, path, data)),
    remove: async (membership) => {
      let removalId: string | undefined;
      try {
        const p = await preview(context, "Remove", {
          membershipId: membership.membershipId,
        });
        const r = await jsonOk(
          await mutate(context, "/api/requests", { previewId: p.id }),
          [200, 201],
        );
        removalId = r.id;
        const pr = await jsonOk(
          await mutate(reviewer, `/api/requests/${r.id}/preview`, {}),
        );
        await jsonOk(
          await mutate(reviewer, `/api/requests/${r.id}/approve`, {
            previewId: pr.id,
          }),
        );
      } finally {
        // If review fails, do not leave our cleanup request pending either.
        if (removalId) await cleanupRequest(context, reviewer, removalId, []);
      }
    },
  });
}

async function stablePage(page: Page, path: string, image: string) {
  await page.goto(`${baseURL}${path}`);
  await expect(page.getByRole("main")).toBeVisible();
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
  await expect(page.locator(".loading")).toHaveCount(0);
  await page.screenshot({ path: resolve(artifacts, image), fullPage: true });
  expect(
    await page.evaluate(
      () => document.documentElement.scrollWidth <= window.innerWidth + 1,
    ),
    "No horizontal overflow",
  ).toBeTruthy();
}

